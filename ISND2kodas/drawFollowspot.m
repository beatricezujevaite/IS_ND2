function outputFrame = drawFollowspot( ...
    frame, ...
    tracks, ...
    currentFPS, ...
    radius, ...
    opacity)
% drawFollowspot
%
% Nupiešia:
%   - pusiau permatomą geltoną followspot
%   - geltoną išorinį kontūrą
%   - bounding box
%   - Track ID
%   - confidence
%   - FPS

    outputFrame = frame;

    %% ========================================================
    % 1. FOLLOWSPOT APSKRITIMAI
    % ========================================================

    for k = 1:numel(tracks)

        % Rodyti tik aktyvius track'us
        if tracks(k).consecutiveInvisibleCount > 0
            continue;
        end

        bbox = tracks(k).bbox;

        %% Objekto centras

        centerX = bbox(1) + bbox(3)/2;
        centerY = bbox(2) + bbox(4)/2;

        %% ----------------------------------------------------
        % Vidinis pusiau permatomas apskritimas
        % -----------------------------------------------------

        circle = [centerX centerY radius];

        outputFrame = insertShape( ...
            outputFrame, ...
            "FilledCircle", ...
            circle, ...
            "Color", "yellow", ...
            "Opacity", opacity);

        %% ----------------------------------------------------
        % Išorinis followspot kontūras
        % -----------------------------------------------------

        outputFrame = insertShape( ...
            outputFrame, ...
            "Circle", ...
            circle, ...
            "Color", "yellow", ...
            "LineWidth", 3);

        %% ----------------------------------------------------
        % Objekto centrinis taškas
        % -----------------------------------------------------

        outputFrame = insertShape( ...
            outputFrame, ...
            "FilledCircle", ...
            [centerX centerY 5], ...
            "Color", "yellow", ...
            "Opacity", 1);

    end

    %% ========================================================
    % 2. BOUNDING BOX IR ID
    % ========================================================

    for k = 1:numel(tracks)

        if tracks(k).consecutiveInvisibleCount > 0
            continue;
        end

        bbox = tracks(k).bbox;

        label = sprintf( ...
            "ID %d | %.2f", ...
            tracks(k).id, ...
            tracks(k).confidence);

        outputFrame = insertObjectAnnotation( ...
            outputFrame, ...
            "rectangle", ...
            bbox, ...
            label, ...
            "Color", ...
            "yellow", ...
            "LineWidth", ...
            2, ...
            "FontSize", ...
            14);

    end

    %% ========================================================
    % 3. FPS ANOTACIJA
    % ========================================================

    fpsText = sprintf( ...
        "FPS: %.1f", ...
        currentFPS);

    outputFrame = insertObjectAnnotation( ...
        outputFrame, ...
        "rectangle", ...
        [10 10 150 35], ...
        fpsText, ...
        "Color", ...
        "yellow", ...
        "LineWidth", ...
        1, ...
        "FontSize", ...
        16);

end